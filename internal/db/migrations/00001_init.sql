CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name text NOT NULL,
    last_name text,
    email text NOT NULL UNIQUE,
    phone text NOT NULL UNIQUE,
    city text NOT NULL,
    language text NOT NULL CHECK (language IN ('tr', 'en')),
    sms_opt_in boolean NOT NULL,
    email_opt_in boolean NOT NULL,
    signed_up_at timestamptz NOT NULL
);

CREATE INDEX users_city_idx ON users (city);

CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id),
    ordered_at timestamptz NOT NULL,
    total_amount numeric(10, 2) NOT NULL CHECK (total_amount >= 0)
);

CREATE INDEX orders_user_ordered_idx ON orders (user_id, ordered_at);

CREATE TABLE order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders (id),
    category text NOT NULL REFERENCES categories (code),
    quantity int NOT NULL CHECK (quantity > 0),
    unit_price numeric(10, 2) NOT NULL CHECK (unit_price >= 0)
);

CREATE INDEX order_items_order_idx ON order_items (order_id);
CREATE INDEX order_items_category_idx ON order_items (category);

CREATE TABLE cart_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id),
    category text NOT NULL REFERENCES categories (code),
    quantity int NOT NULL CHECK (quantity > 0),
    unit_price numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
    added_at timestamptz NOT NULL
);

CREATE INDEX cart_items_user_added_idx ON cart_items (user_id, added_at);

-- One row once seeded; its presence makes the seed a no-op (D28).
CREATE TABLE seed_meta (
    id int PRIMARY KEY CHECK (id = 1),
    rng_seed bigint NOT NULL,
    reference_time timestamptz NOT NULL,
    seeded_at timestamptz NOT NULL DEFAULT now()
);

-- Marketers and sessions (D10)

CREATE TABLE marketers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    name text NOT NULL,
    password_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sessions (
    token_hash bytea PRIMARY KEY,
    marketer_id bigint NOT NULL REFERENCES marketers (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);

CREATE INDEX sessions_expires_idx ON sessions (expires_at);

-- Campaigns (D1, D11, D29–D31)

CREATE TABLE campaigns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_text text NOT NULL,
    channels text[] NOT NULL CHECK (cardinality(channels) > 0 AND channels <@ ARRAY['sms', 'email']),
    rules jsonb,                        -- NULL only on a resend
    status text NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'approved', 'sending', 'completed', 'cancelled')),
    version int NOT NULL DEFAULT 1,
    send_at timestamptz,                -- draft: proposed time; fixed at approval
    schedule_note text,
    time_zone text NOT NULL,            -- IANA zone from the browser
    parent_campaign_id bigint REFERENCES campaigns (id),
    approval_estimate jsonb,
    audience_built_at timestamptz,
    created_by bigint NOT NULL REFERENCES marketers (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    approved_by bigint REFERENCES marketers (id),
    approved_at timestamptz,
    cancelled_by bigint REFERENCES marketers (id),
    cancelled_at timestamptz,
    completed_at timestamptz,
    CHECK (parent_campaign_id IS NULL OR cardinality(channels) = 1)
);

-- At most one active resend per parent and channel (D31).
CREATE UNIQUE INDEX campaigns_one_active_resend_idx ON campaigns (parent_campaign_id, channels)
    WHERE parent_campaign_id IS NOT NULL AND status <> 'cancelled';
CREATE INDEX campaigns_due_idx ON campaigns (send_at) WHERE status = 'approved';

CREATE TABLE campaign_content (
    campaign_id bigint NOT NULL REFERENCES campaigns (id),
    channel text NOT NULL CHECK (channel IN ('sms', 'email')),
    subject text,
    body text NOT NULL,
    PRIMARY KEY (campaign_id, channel)
);

-- Delivery tracking: the messages table is the queue (D4, D5, D18)

CREATE TABLE messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id bigint NOT NULL REFERENCES campaigns (id),
    user_id bigint NOT NULL REFERENCES users (id),
    channel text NOT NULL CHECK (channel IN ('sms', 'email')),
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'sending', 'retry_scheduled', 'sent', 'failed', 'skipped', 'cancelled')),
    skip_reason text CHECK (skip_reason IN ('no_consent', 'character_limit_exceeded')),
    last_error text,
    attempt_count int NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    lease_token uuid,
    lease_expires_at timestamptz,
    sent_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (campaign_id, user_id, channel),
    CHECK ((status = 'skipped') = (skip_reason IS NOT NULL))
);

CREATE INDEX messages_due_idx ON messages (channel, next_attempt_at)
    WHERE status IN ('pending', 'retry_scheduled');
CREATE INDEX messages_lease_idx ON messages (lease_expires_at) WHERE status = 'sending';
CREATE INDEX messages_campaign_status_idx ON messages (campaign_id, status);

CREATE TABLE delivery_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id bigint NOT NULL REFERENCES messages (id),
    attempt_no int NOT NULL,
    started_at timestamptz NOT NULL,
    finished_at timestamptz,
    outcome text CHECK (outcome IN ('accepted', 'rate_limited', 'server_error', 'timeout', 'network_error', 'rejected')),
    http_status int,
    error text,
    UNIQUE (message_id, attempt_no)
);

